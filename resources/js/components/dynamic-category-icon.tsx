export const ICON_MAP = ICONS_BY_NAME;

interface DynamicCategoryIconProps extends Omit<React.SVGProps<SVGSVGElement>, 'name'> {
    name?: string | null;
    className?: string;
    fallback?: LucideIcon;
}

export function DynamicCategoryIcon({
    name,
    className = 'w-6 h-6',
    fallback = Coffee,
    ...props
}: DynamicCategoryIconProps) {
    if (!name) {
        const FallbackComponent = fallback;
        return <FallbackComponent className={className} {...props} />;
    }

    // Strip package prefixes: 'lucide-', 'heroicon-c-', 'heroicon-o-', 'heroicon-s-', 'heroicon-m-', 'heroicon-', 'blade-'
    const clean = name.toLowerCase().replace(/^(lucide|heroicon-[a-z0-9]+|heroicon|blade)-/, '').trim();

    // Enforce banned icon rule
    if (clean === 'sparkles' || clean === 'sparkle') {
        return <Star className={className} {...props} />;
    }

    // Direct lookup in curated map
    const IconComponent = ICONS_BY_NAME[clean] || ICONS_BY_NAME[clean.replace(/-/g, '')];
    if (IconComponent) {
        return <IconComponent className={className} {...props} />;
    }

    const FallbackComponent = fallback;
    return <FallbackComponent className={className} {...props} />;
}

export default DynamicCategoryIcon;
